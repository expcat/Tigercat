#!/usr/bin/env node

import { spawnSync } from 'node:child_process'
import { readFileSync, rmSync } from 'node:fs'
import { join } from 'node:path'
import { assertSsrArtifacts } from './lib/ssr-artifacts.mjs'

const root = join(import.meta.dirname, '..')
const nextEnvPath = join(root, 'examples/nextjs/next-env.d.ts')

const pnpmExecPath = process.env.npm_execpath
const command = pnpmExecPath ? process.execPath : process.platform === 'win32' ? 'pnpm.cmd' : 'pnpm'
const args = pnpmExecPath ? [pnpmExecPath, 'example:ssr:build'] : ['example:ssr:build']

function fail(message, code = 1) {
  const error = new Error(message)
  error.exitCode = code
  throw error
}

function run(spawnArgs) {
  const result = spawnSync(command, spawnArgs, {
    cwd: root,
    stdio: 'inherit'
  })

  if (result.error) fail(result.error.message)
  if (result.status !== 0) fail(`command failed: ${spawnArgs.join(' ')}`, result.status ?? 1)
}

function cleanupBuildOutput() {
  rmSync(join(root, 'examples/nextjs/.next'), { recursive: true, force: true })
  rmSync(join(root, 'examples/nuxt/.output'), { recursive: true, force: true })
  rmSync(join(root, 'examples/nuxt/.nuxt'), { recursive: true, force: true })
}

let exitCode = 0
try {
  const before = readFileSync(nextEnvPath, 'utf8')
  run(args)

  const after = readFileSync(nextEnvPath, 'utf8')
  if (before !== after) {
    fail(
      'examples/nextjs/next-env.d.ts changed during SSR example build. Keep this file in the format generated by Next.js before running the check again.'
    )
  }

  assertSsrArtifacts('next', join(root, 'examples/nextjs'))
  assertSsrArtifacts('nuxt', join(root, 'examples/nuxt'))

  run(
    pnpmExecPath
      ? [pnpmExecPath, 'vitest', 'run', 'tests/core/ssr-frameworks.spec.ts']
      : ['vitest', 'run', 'tests/core/ssr-frameworks.spec.ts']
  )

  console.log(
    'SSR example component markers (Button, DatePicker, BarChart), next-env.d.ts, and hydration checks passed.'
  )
} catch (error) {
  exitCode = error.exitCode ?? 1
  console.error(error.message ?? error)
} finally {
  cleanupBuildOutput()
}

process.exit(exitCode)
