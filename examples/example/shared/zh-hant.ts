export function toZhHant(text: string): string {
  let next = text
  for (const [from, to] of PHRASES) {
    if (next.includes(from)) next = next.split(from).join(to)
  }
  let out = ''
  for (const ch of next) out += CHARS[ch] ?? ch
  return out
}

export function demoCopy(copy: DemoCopy, lang: DemoLang): string {
  if (lang === 'en-US') return copy['en-US']
  if (lang === 'zh-TW') return toZhHant(copy['zh-CN'])
  return copy['zh-CN']
}

/** Page and demo descriptions. English has no parallel prose. */
export function demoProse(text: string | undefined, lang: DemoLang): string | undefined {
  if (!text || lang === 'en-US') return undefined
  return lang === 'zh-TW' ? toZhHant(text) : text
}
